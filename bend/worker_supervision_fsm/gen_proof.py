    st_cases = []
    for st, fields in STATES:
        plus = ", ".join("+" + f.strip() for f in fields.split(","))
        plain = ", ".join(f.strip() for f in fields.split(","))
        if st in body:
            b = f"reap_{st.lower()}({plain}, e, lim, k)"
