"""Write PROOF.bend. Bend's checker does not refine a wildcard `case _:` in
a proof, so every proof that splits on an event spells out all ten worker
event constructors (and every state where it splits on the state). This
script stamps those cases; the proof logic is the `special` cases below.
Re-run after editing, then `bend PROOF.bend`.
"""
from pathlib import Path

EVENTS = [
    ("Start", "h, t"), ("Beat", "t"), ("Spawn", ""), ("Reap", ""), ("Tick", "now"),
    ("Finish", ""), ("Interrupt", "t"), ("Resume", "by, log"), ("Abandon", ""), ("Integrate", ""),
]
STATES = [
    ("Dispatched", "w"), ("Running", "w, h, hb, bg"), ("Stalled", "w, h, hb, bg"),
    ("Interrupted", "w, at, bg"), ("Overdue", "w, at, bg"), ("Completed", "w, bg"),
    ("Resumed", "w, by, bg"), ("Abandoned", "w"), ("Integrated", "w"),
]


def cases(special: dict[str, tuple[str, str]], default: str, indent: str = "    ") -> str:
    """match-e cases: special[name] = (pattern fields, body); others get default."""
    out = []
    for name, fields in EVENTS:
        pat, body = special.get(name, (fields, default))
        out.append(f"{indent}case F.{name}{{{pat}}}:\n{indent}  {body}")
    return "\n".join(out)


