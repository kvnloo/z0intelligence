#!/usr/bin/env python3
"""Generate the O18 (privacy-tier model routing) sections of ops.bend, LAWS.bend and PROOF.bend.

The kernel and laws are hand-written text below; only the exhaustive case-split proofs are
generated, from the Python twin (src/z0int/fsm/ops.py) and the independent spec in LAWS. A wrong
twin cannot make a false law pass: Bend re-checks every generated leaf against ops.bend.

    python3 bend/ops_fsm/gen_o18.py          # rewrite the three O18 sections in place
"""
from __future__ import annotations

import itertools
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "src"))
from z0int.fsm import ops as P  # noqa: E402

BEGIN, END = "# >>> O18 privacy route (generated by gen_o18.py)", "# <<< O18 privacy route"

TIERS = [(P.Tier.PUBLIC, "PtPublic"), (P.Tier.PERSONAL, "PtPersonal"), (P.Tier.UNKNOWN, "PtUnknown"),
         (P.Tier.SENSITIVE, "PtSensitive"), (P.Tier.THIRD, "PtThird"), (P.Tier.SECRET, "PtSecret")]
LANES = [(P.MLane.LOCAL, "PlLocal"), (P.MLane.PAID, "PlPaid"), (P.MLane.FREE_OK, "PlFreeOk"),
         (P.MLane.FREE_PUB, "PlFreePub")]
TASKS = [(P.Task.AGENTIC, "PkAgentic"), (P.Task.SIMPLE, "PkSimple")]
B2 = [(True, "True{}"), (False, "False{}")]

OPS = '''# ------------------------------------------------------------------ O18
# Privacy-tier model routing. The owner's tier table (sft-svlm/data/privacy
# README, pol-1.2, approved 2026-10-20): public data may go anywhere; personal
# (T1) data to local, his paid subscriptions (Claude/ChatGPT/Codex/Grok) or the
# approved free lane (Cerebras), never to a free lane that may train on it;
# sensitive (T2), third-party (T3) and unclassified data stay local; secrets
# (T4) go to no model. Free lanes take only simple, non-agentic work. Agentic
# T0/T1 work runs on a paid lane or waits; it never falls back to the weak
# local model. Which lanes are up, and what tier a request carries, are host
# facts (Python side: router /v1/models, path and content classifiers).
type PTier is Data:
  PtPublic{}
  PtPersonal{}
  PtUnknown{}
  PtSensitive{}
  PtThird{}
  PtSecret{}

type PLane is Data:
  PlLocal{}
  PlPaid{}
  PlFreeOk{}
  PlFreePub{}

type PTask is Data:
  PkAgentic{}
  PkSimple{}

type PRoute is Data:
  PrUse{l: PLane}
  PrQueue{}
  PrRefuse{}

def tier_rank(t: PTier) -> Nat:
  match t:
    case PtPublic{}:
      0n
    case PtPersonal{}:
      1n
    case PtUnknown{}:
      2n
    case PtSensitive{}:
      3n
    case PtThird{}:
      4n
    case PtSecret{}:
      5n

def join_by(gt: Bool, a: PTier, b: PTier) -> PTier:
  match gt:
    case True{}:
      b
    case False{}:
      a

# taint: a request carries the more restrictive of two tiers
def tier_join(+a: PTier, +b: PTier) -> PTier:
  join_by(Nat.is_gt(tier_rank(b), tier_rank(a)), a, b)

def personal_allows(l: PLane) -> Bool:
  match l:
    case PlFreePub{}:
      False{}
    case _:
      True{}

def local_lane(l: PLane) -> Bool:
  match l:
    case PlLocal{}:
      True{}
    case _:
      False{}

def tier_allows(t: PTier, l: PLane) -> Bool:
  match t:
    case PtPublic{}:
      True{}
    case PtPersonal{}:
      personal_allows(l)
    case PtSecret{}:
      False{}
    case _:
      local_lane(l)

def task_fits(k: PTask, l: PLane) -> Bool:
  match k:
    case PkSimple{}:
      True{}
    case PkAgentic{}:
      match l:
        case PlPaid{}:
          True{}
        case PlLocal{}:
          True{}
        case _:
          False{}

def lane_ok(t: PTier, k: PTask, +l: PLane, up: Bool) -> Bool:
  Bool.and(up, Bool.and(tier_allows(t, l), task_fits(k, l)))

def pick(ok: Bool, l: PLane, rest: PRoute) -> PRoute:
  match ok:
    case True{}:
      PrUse{l}
    case False{}:
      rest

# agentic: the paid lane when the tier allows it, else local; never the other
def agentic_by(paid_ok: Bool, +t: PTier, loc: Bool, paid: Bool) -> PRoute:
  match paid_ok:
    case True{}:
      pick(lane_ok(t, PkAgentic{}, PlPaid{}, paid), PlPaid{}, PrQueue{})
    case False{}:
      pick(lane_ok(t, PkAgentic{}, PlLocal{}, loc), PlLocal{}, PrQueue{})

# simple: approved free, public free, local, paid; first allowed lane that is up
def route_simple(+t: PTier, loc: Bool, paid: Bool, fok: Bool, fpub: Bool) -> PRoute:
  pick(lane_ok(t, PkSimple{}, PlFreeOk{}, fok), PlFreeOk{},
    pick(lane_ok(t, PkSimple{}, PlFreePub{}, fpub), PlFreePub{},
      pick(lane_ok(t, PkSimple{}, PlLocal{}, loc), PlLocal{},
        pick(lane_ok(t, PkSimple{}, PlPaid{}, paid), PlPaid{}, PrQueue{}))))

def route_open(+t: PTier, k: PTask, loc: Bool, paid: Bool, fok: Bool, fpub: Bool) -> PRoute:
  match k:
    case PkAgentic{}:
      agentic_by(tier_allows(t, PlPaid{}), t, loc, paid)
    case PkSimple{}:
      route_simple(t, loc, paid, fok, fpub)

# where a request of tier t and task k goes, given which lanes are up
def route(+t: PTier, k: PTask, loc: Bool, paid: Bool, fok: Bool, fpub: Bool) -> PRoute:
  match t:
    case PtSecret{}:
      PrRefuse{}
    case _:
      route_open(t, k, loc, paid, fok, fpub)
'''

LAWS = '''# O18. Privacy-tier model routing
# --------------------------------
# Written apart from ops.bend: the owner's tier table (pol-1.2).
def o18_allows(t: O.PTier, l: O.PLane) -> Bool:
  match t:
    case O.PtPublic{}:
      True{}
    case O.PtPersonal{}:
      match l:
        case O.PlLocal{}:
          True{}
        case O.PlPaid{}:
          True{}
        case O.PlFreeOk{}:
          True{}
        case O.PlFreePub{}:
          False{}
    case O.PtUnknown{}:
      match l:
        case O.PlLocal{}:
          True{}
        case _:
          False{}
    case O.PtSensitive{}:
      match l:
        case O.PlLocal{}:
          True{}
        case _:
          False{}
    case O.PtThird{}:
      match l:
        case O.PlLocal{}:
          True{}
        case _:
          False{}
    case O.PtSecret{}:
      False{}

def o18_free(l: O.PLane) -> Bool:
  match l:
    case O.PlFreeOk{}:
      True{}
    case O.PlFreePub{}:
      True{}
    case _:
      False{}

def o18_fits(k: O.PTask, l: O.PLane) -> Bool:
  match k:
    case O.PkSimple{}:
      True{}
    case O.PkAgentic{}:
      Bool.not(o18_free(l))

def o18_up(l: O.PLane, loc: Bool, paid: Bool, fok: Bool, fpub: Bool) -> Bool:
  match l:
    case O.PlLocal{}:
      loc
    case O.PlPaid{}:
      paid
    case O.PlFreeOk{}:
      fok
    case O.PlFreePub{}:
      fpub

# a chosen lane is allowed for the tier, fits the task and is up; waiting and
# refusing never send data anywhere
def o18_lane_sound(t: O.PTier, k: O.PTask, loc: Bool, paid: Bool, fok: Bool, fpub: Bool, +l: O.PLane) -> Bool:
  Bool.and(o18_allows(t, l), Bool.and(o18_fits(k, l), o18_up(l, loc, paid, fok, fpub)))

def o18_sound(t: O.PTier, k: O.PTask, loc: Bool, paid: Bool, fok: Bool, fpub: Bool, r: O.PRoute) -> Bool:
  match r:
    case O.PrUse{l}:
      o18_lane_sound(t, k, loc, paid, fok, fpub, l)
    case O.PrQueue{}:
      True{}
    case O.PrRefuse{}:
      True{}

def o18_not_free(r: O.PRoute) -> Bool:
  match r:
    case O.PrUse{l}:
      Bool.not(o18_free(l))
    case _:
      True{}

def o18_not_local(r: O.PRoute) -> Bool:
  match r:
    case O.PrUse{l}:
      match l:
        case O.PlLocal{}:
          False{}
        case _:
          True{}
    case _:
      True{}

# every route is sound, for every tier, task and lane availability
law o18_route_sound:
  for t: O.PTier
  for k: O.PTask
  for loc: Bool
  for paid: Bool
  for fok: Bool
  for fpub: Bool
  T(o18_sound(t, k, loc, paid, fok, fpub, O.route(t, k, loc, paid, fok, fpub)))

# secrets go to no model, whatever is up
law o18_secret_refused:
  for k: O.PTask
  for loc: Bool
  for paid: Bool
  for fok: Bool
  for fpub: Bool
  {O.route(O.PtSecret{}, k, loc, paid, fok, fpub) == O.PrRefuse{} : O.PRoute}

# free lanes never take agentic (tool/code) work
law o18_free_never_agentic:
  for t: O.PTier
  for loc: Bool
  for paid: Bool
  for fok: Bool
  for fpub: Bool
  T(o18_not_free(O.route(t, O.PkAgentic{}, loc, paid, fok, fpub)))

# agentic public/personal work never falls back to the local model
law o18_agentic_no_weak_fallback:
  for loc: Bool
  for paid: Bool
  for fok: Bool
  for fpub: Bool
  T(o18_not_local(O.route(O.PtPersonal{}, O.PkAgentic{}, loc, paid, fok, fpub)))

law o18_personal_agentic_waits_for_paid:
  {O.route(O.PtPersonal{}, O.PkAgentic{}, True{}, False{}, True{}, True{}) == O.PrQueue{} : O.PRoute}

law o18_personal_agentic_paid:
  {O.route(O.PtPersonal{}, O.PkAgentic{}, True{}, True{}, True{}, True{}) == O.PrUse{O.PlPaid{}} : O.PRoute}

law o18_sensitive_agentic_local:
  {O.route(O.PtSensitive{}, O.PkAgentic{}, True{}, True{}, True{}, True{}) == O.PrUse{O.PlLocal{}} : O.PRoute}

law o18_unknown_agentic_local:
  {O.route(O.PtUnknown{}, O.PkAgentic{}, True{}, True{}, True{}, True{}) == O.PrUse{O.PlLocal{}} : O.PRoute}

# sensitive work with the local model down waits; it never goes to the cloud
law o18_sensitive_waits_without_local:
  for k: O.PTask
  for paid: Bool
  for fok: Bool
  for fpub: Bool
  {O.route(O.PtSensitive{}, k, False{}, paid, fok, fpub) == O.PrQueue{} : O.PRoute}

law o18_public_simple_prefers_free:
  {O.route(O.PtPublic{}, O.PkSimple{}, True{}, True{}, True{}, True{}) == O.PrUse{O.PlFreeOk{}} : O.PRoute}

law o18_public_simple_uses_public_free:
  {O.route(O.PtPublic{}, O.PkSimple{}, True{}, True{}, False{}, True{}) == O.PrUse{O.PlFreePub{}} : O.PRoute}

# personal data skips a free lane that may train on prompts
law o18_personal_simple_skips_public_free:
  {O.route(O.PtPersonal{}, O.PkSimple{}, True{}, True{}, False{}, True{}) == O.PrUse{O.PlLocal{}} : O.PRoute}

# taint: the joined tier allows a lane only if both parts do
law o18_join_sound_left:
  for a: O.PTier
  for b: O.PTier
  for l: O.PLane
  for w: T(O.tier_allows(O.tier_join(a, b), l))
  T(o18_allows(a, l))

law o18_join_sound_right:
  for a: O.PTier
  for b: O.PTier
  for l: O.PLane
  for w: T(O.tier_allows(O.tier_join(a, b), l))
  T(o18_allows(b, l))

law o18_join_secret:
  for a: O.PTier
  {O.tier_join(a, O.PtSecret{}) == O.PtSecret{} : O.PTier}
'''


def spec_allows(t, lane):
    if t is P.Tier.PUBLIC:
        return True
    if t is P.Tier.PERSONAL:
        return lane is not P.MLane.FREE_PUB
    if t is P.Tier.SECRET:
        return False
    return lane is P.MLane.LOCAL


def flat(name: str, params: list[str], combos, leaf) -> str:
    lines = [f"def Laws.{name}({', '.join(params)}):", f"  match {' '.join(p for p in params if p != 'w')}:"]
    for combo in combos:
        pats = " ".join(c[1] for c in combo)
        lines.append(f"    case {pats}:")
        lines.append(f"      {leaf([c[0] for c in combo])}")
    return "\n".join(lines) + "\n"


def qual(pairs):
    return [(v, f"O.{s}{{}}") for v, s in pairs]


def proofs() -> str:
    T, L, K = qual(TIERS), qual(LANES), qual(TASKS)
    out = ["# O18. Generated by gen_o18.py: exhaustive case splits; every leaf is checked by Bend.\n"]
    out.append(flat("o18_route_sound", ["t", "k", "loc", "paid", "fok", "fpub"],
                    itertools.product(T, K, B2, B2, B2, B2), lambda _: "Unit{}"))
    out.append(flat("o18_secret_refused", ["k", "loc", "paid", "fok", "fpub"],
                    itertools.product(K, B2, B2, B2, B2), lambda _: "{==}"))
    out.append(flat("o18_free_never_agentic", ["t", "loc", "paid", "fok", "fpub"],
                    itertools.product(T, B2, B2, B2, B2), lambda _: "Unit{}"))
    out.append(flat("o18_agentic_no_weak_fallback", ["loc", "paid", "fok", "fpub"],
                    itertools.product(B2, B2, B2, B2), lambda _: "Unit{}"))
    for nm in ("o18_personal_agentic_waits_for_paid", "o18_personal_agentic_paid", "o18_sensitive_agentic_local",
               "o18_unknown_agentic_local", "o18_public_simple_prefers_free", "o18_public_simple_uses_public_free",
               "o18_personal_simple_skips_public_free"):
        out.append(f"def Laws.{nm}():\n  {{==}}\n")
    out.append(flat("o18_sensitive_waits_without_local", ["k", "paid", "fok", "fpub"],
                    itertools.product(K, B2, B2, B2), lambda _: "{==}"))

    def join_leaf(side):
        def leaf(v):
            a, b, lane = v
            return "Unit{}" if spec_allows(a if side == "l" else b, lane) else "w"
        return leaf
    out.append(flat("o18_join_sound_left", ["a", "b", "l", "w"], itertools.product(T, T, L), join_leaf("l")))
    out.append(flat("o18_join_sound_right", ["a", "b", "l", "w"], itertools.product(T, T, L), join_leaf("r")))
    out.append(flat("o18_join_secret", ["a"], itertools.product(T), lambda _: "{==}"))
    return "\n".join(out)


def splice(path: Path, body: str) -> None:
    text = path.read_text()
    block = f"{BEGIN}\n{body.rstrip()}\n{END}\n"
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n\n" + block
    path.write_text(text)


if __name__ == "__main__":
    splice(HERE / "ops.bend", OPS)
    splice(HERE / "LAWS.bend", LAWS)
    splice(HERE / "PROOF.bend", proofs())
    print("O18 sections written")
