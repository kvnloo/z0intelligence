"""Write PROOF.bend. Bend's checker does not refine a wildcard `case _:` in
a proof, so every proof that splits on an event spells out all fifteen
event constructors. This script stamps those cases; the proof logic is the
`special` cases written below. Re-run after editing, then `bend PROOF.bend`.
"""
