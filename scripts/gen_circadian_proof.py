#!/usr/bin/env python3
"""Generate bend/circadian/PROOF.bend: every law proven by full case analysis.

The gate has a finite domain (8 phases x 4 classes x 2^5 flags), so each law
is proven by splitting on its variables. In each case either a hypothesis
computes to Empty (closed by an empty match) or the claim computes to a
reflexive equality / Unit. The generator decides which with the Python twin,
then Bend re-checks every case by computation: a wrong twin cannot produce a
proof Bend accepts. Run: python3 scripts/gen_circadian_proof.py
"""
from __future__ import annotations

import itertools
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from z0int.human_posture import PHASES, QUIET, gate  # noqa: E402

BEND = {"SLEEP": "Sleep", "INERTIA": "Inertia", "PEAK": "Peak", "DIP": "Dip", "SECOND": "Second",
        "WIND_DOWN": "WindDown", "PRE_SLEEP": "PreSleep", "DISENGAGED": "Disengaged"}
SOUND = {"PEAK"}


def deliver(p, cls, v):
    return gate(p, cls, v["a"], v["i"], v["o"], v["t"], v["k"]) == "deliver"


# name, split vars, fixed values, hypotheses [(binder, predicate)], conclusion (kind, predicate)
LAWS = [
    ("quiet_no_decisions", "paiotk", {}, [("q", lambda v: v["p"] in QUIET)], ("eq", lambda v: not deliver(v["p"], "decision", v))),
    ("quiet_no_reports", "paiotk", {}, [("q", lambda v: v["p"] in QUIET)], ("eq", lambda v: not deliver(v["p"], "report", v))),
    ("quiet_no_digests", "paiotk", {}, [("q", lambda v: v["p"] in QUIET)], ("eq", lambda v: not deliver(v["p"], "digest", v))),
    ("quiet_critical_narrow", "paiotk", {},
     [("q", lambda v: v["p"] in QUIET), ("w", lambda v: deliver(v["p"], "critical", v))],
     ("unit", lambda v: v["a"] and v["i"] and v["o"])),
    ("cap_holds_reports", "paiot", {"k": False}, [], ("eq", lambda v: not deliver(v["p"], "report", v))),
    ("cap_holds_decisions", "paiot", {"k": False}, [], ("eq", lambda v: not deliver(v["p"], "decision", v))),
    ("sound_only_in_peak", "p", {}, [("w", lambda v: v["p"] in SOUND)], ("eq", lambda v: v["p"] == "PEAK")),
    ("decisions_only_peak_or_plan", "paiotk", {}, [("w", lambda v: deliver(v["p"], "decision", v))],
     ("unit", lambda v: v["p"] == "PEAK" or (v["p"] == "SECOND" and v["t"]))),
]


def pat(var, val):
    if var == "p":
        return f"G.{BEND[val]}{{}}"
    return "True{}" if val else "False{}"


def proof(name, split, fixed, hyps, concl):
    params = list(split) + [h for h, _ in hyps]
    lines = [f"def Laws.{name}({', '.join(params)}):", f"  match {' '.join(split)}:"]
    domains = [PHASES if s == "p" else (True, False) for s in split]
    for combo in itertools.product(*domains):
        v = {"a": False, "i": False, "o": False, "t": False, "k": False, **fixed, **dict(zip(split, combo))}
        lines.append("    case " + " ".join(pat(s, x) for s, x in zip(split, combo)) + ":")
        dead = next((h for h, pred in hyps if not pred(v)), None)
        if dead:
            lines.append(f"      match {dead}:")
            continue
        kind, pred = concl
        if not pred(v):
            raise SystemExit(f"law {name} is false at {v}: the Python twin violates it")
        lines.append("      {==}" if kind == "eq" else "      Unit{}")
    return "\n".join(lines)


def main() -> None:
    out = ["# GENERATED by scripts/gen_circadian_proof.py. Do not edit; regenerate.",
           "# Each law is proven by full case analysis over its finite variables.", "",
           "import Base", "import ./gate.bend as G", "import ./LAWS.bend as Laws", ""]
    for law in LAWS:
        out.append(proof(*law))
        out.append("")
    (ROOT / "bend" / "circadian" / "PROOF.bend").write_text("\n".join(out))


if __name__ == "__main__":
    main()
