"""Human-readable and machine-readable layers of the work-item statechart.

* `mermaid()` renders work_item.TRANSITIONS as a Mermaid stateDiagram (the
  diagram is generated from the same table the checker runs, so it cannot
  drift from the code).
* `overlay()` is the data contract for a Company OS overlay layer: the
  statechart, the laws with their proof receipt, and the live state of each
  item from a replay report. Company OS renders it; it does not decide.

    PYTHONPATH=src python -m z0int.fsm.export --mermaid docs/fsm/work-item.mmd
    PYTHONPATH=src python -m z0int.fsm.export --report report.json \\
        --receipt bend/work_item_fsm/receipt.json --overlay overlay.json
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from .work_item import LAWS, TERMINAL, TRANSITIONS, Phase, Role

ROLE_NOTES = {
    "owner": "Kevin: goals, taste, physical world, credentials, irreversible approvals (batched queue)",
    "opus": "frontier lane: design, verification, hard code, orchestration",
    "sol": "Sol on pi/SoL-Pi (MBP) or omp: bulk well-specified coding",
    "chat": "ChatGPT app / Grok / Muse: advice and specs; no sandbox, no origin actions",
    "free": "free models: scans, triage, summaries checked by code; never code",
    "jev": "picks/ranks/gates among prevalidated options; never writes",
    "slm": "shadow network; shadow-only until promoted by matched evidence",
    "ci": "deterministic code: CI, tests, service-branch check, replay checker",
}

SIDE = {"Blocked", "Interrupted", "Abandoned"}


def mermaid() -> str:
    lines = [
        "%% Work-item lifecycle v0. Generated by `python -m z0int.fsm.export --mermaid`",
        "%% from src/z0int/fsm/work_item.py TRANSITIONS; laws L1-L7 are proven in",
        "%% bend/work_item_fsm (PROOF.bend). Edge label: event [roles] (law).",
        "stateDiagram-v2",
        "    direction LR",
        "    [*] --> Proposed",
    ]
    for t in TRANSITIONS:
        roles = ",".join(t["roles"])
        law = f" L{t['law']}" if t.get("law") else ""
        label = f"{t['event']} [{roles}]{law}".replace(":", " ")
        lines.append(f"    {t['from']} --> {t['to']} : {label}")
    lines += ["    Merged --> [*]", "    Abandoned --> [*]",
              "    note right of Deployed",
              "        needs-Kevin queue (L7): acceptance waits for his next",
              "        deep-work block or low-energy phone review; other items keep moving",
              "    end note",
              "    note left of Interrupted",
              "        L5: leaves only by Resume (head kept) or Abandon;",
              "        replay checker flags any left past the TTL",
              "    end note",
              "    classDef side fill:#2a2a2a,stroke:#c77,color:#eee",
              "    classDef owner fill:#24324a,stroke:#7af,color:#eee",
              "    class Blocked,Interrupted,Abandoned side",
              "    class OwnerAccepted owner"]
    return "\n".join(lines) + "\n"


def statechart() -> dict[str, Any]:
    return {
        "states": [{"id": p.value, "terminal": p in TERMINAL, "side": p.value in SIDE,
                    "needs_owner": p is Phase.DEPLOYED} for p in Phase],
        "initial": Phase.PROPOSED.value,
        "transitions": TRANSITIONS,
        "laws": LAWS,
        "roles": [{"id": r.value, "note": ROLE_NOTES[r.value]} for r in Role],
        "owner_availability": ["available_deep_work", "low_energy", "off"],
    }


def overlay(report: dict | None, receipt: dict | None) -> dict[str, Any]:
    proof = None
    if receipt:
        proof = {k: receipt.get(k) for k in (
            "receipt_id", "verdict", "verified_at", "bend_version", "input_manifest_sha256",
            "proof_sha256", "verification_scope", "source_semantics_attested")}
        proof["laws_scope"] = "theorems about bend/work_item_fsm/fsm.bend only; not the replay checker or the world"
    items = []
    for it in (report or {}).get("items", []):
        fs = it.get("findings", [])
        items.append({
            "id": it["id"], "kind": it["kind"], "title": it["title"], "phase": it["phase"],
            "needs_kevin": it["needs_kevin"],
            "url": it.get("meta", {}).get("url"),
            "repo": it.get("meta", {}).get("repo"),
            "violations": [{"law": f["law"], "code": f["code"], "message": f["message"]}
                           for f in fs if f["severity"] == "violation"],
            "indeterminate": [f["code"] for f in fs if f["severity"] == "indeterminate"],
            "candidates": [f["code"] for f in fs if f["severity"] == "candidate"],
        })
    return {
        "schema": "z0.fsm.work-item.overlay/v0",
        "layer": "statechart",
        "render_hint": "xyflow: one node per state; items as badges on their state; red edge = refused move",
        "statechart": statechart(),
        "proof": proof,
        "generated_at": (report or {}).get("generated_at"),
        "summary": (report or {}).get("summary"),
        "needs_kevin": (report or {}).get("needs_kevin"),
        "items": items,
        "authority": "display only: no field here authorizes, admits or marks verified_success",
    }


def public_summary(report: dict) -> dict[str, Any]:
    """What may be published: counts, public PR numbers, branch names and
    SHAs. No local paths, no worker goals or logs (they are personal traces)."""
    prs, services, workers = [], [], {}
    for it in report["items"]:
        for f in it["findings"]:
            if it["kind"] == "pr":
                prs.append({"pr": it["id"], "law": f["law"], "code": f["code"], "severity": f["severity"]})
            elif it["kind"] == "worker":
                workers.setdefault(f["code"], 0)
                workers[f["code"]] += 1
        if it["kind"] == "service":
            served = it["meta"].get("served") or {}
            services.append({
                "service": it["id"], "port": it["meta"]["port"], "repo": it["meta"]["repo"],
                "integration_ref": it["meta"]["integration_ref"], "phase": it["phase"],
                "served_branch": served.get("branch"), "served_head": served.get("head"),
                "dirty_files": served.get("dirty_files"), "integration_head": it["meta"].get("integration_head"),
                "findings": [{"law": f["law"], "code": f["code"],
                              "behind": f["evidence"].get("behind"), "ahead": f["evidence"].get("ahead"),
                              "merged_prs_not_served": [p["number"] for p in f["evidence"].get("merged_prs_not_served", [])]}
                             for f in it["findings"]],
            })
    ends: dict[str, int] = {}
    for it in report["items"]:
        if it["kind"] == "worker":
            ends[it["meta"]["end"]] = ends.get(it["meta"]["end"], 0) + 1
    return {
        "schema": "z0.fsm.work-item.replay-public/v0",
        "generated_at": report["generated_at"],
        "summary": report["summary"],
        "items_by_kind": {k: sum(1 for it in report["items"] if it["kind"] == k) for k in ("pr", "service", "worker")},
        "services": services,
        "pr_findings": prs,
        "workers": {"interrupted_or_vanished_by_end": ends, "findings": workers},
        "checkout_sweep": [{"repo": r["repo"], "branch": r["branch"], "head": r["head"],
                            "would_miss_merged_prs": [p["number"] for p in r["would_miss_merged_prs"]]}
                           for r in report.get("checkout_sweep", [])],
        "needs_kevin": {k: report["needs_kevin"][k] for k in ("owner_availability", "held_until_next_block", "size")}
        | {"items": [i["id"] for i in report["needs_kevin"]["items"]]},
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--public", type=Path, help="write the publishable summary of --report")
    ap.add_argument("--mermaid", type=Path)
    ap.add_argument("--report", type=Path)
    ap.add_argument("--receipt", type=Path)
    ap.add_argument("--overlay", type=Path)
    a = ap.parse_args(argv)
    if a.mermaid:
        a.mermaid.parent.mkdir(parents=True, exist_ok=True)
        a.mermaid.write_text(mermaid())
    if a.overlay:
        rep = json.loads(a.report.read_text()) if a.report else None
        rec = json.loads(a.receipt.read_text()) if a.receipt else None
        a.overlay.write_text(json.dumps(overlay(rep, rec), indent=1, default=str) + "\n")
    if a.public and a.report:
        a.public.write_text(json.dumps(public_summary(json.loads(a.report.read_text())), indent=1) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
